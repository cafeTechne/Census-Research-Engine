"""Round 118: Automated offline pre-commit release-hygiene & packaging check for Rounds 103-118."""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import census
from census import inflation, pipeline, rpp
from census.manifest.methods import METHODS
from census.references import SOURCES


def check_all() -> dict:
    errors = []

    # 1. Version parity across __init__.py, pipeline.py, CITATION.cff
    v_init = census.__version__
    v_pipe = pipeline.PACKAGE_VERSION
    cit_text = (ROOT / "CITATION.cff").read_text(encoding="utf-8")
    m_cit = re.search(r'^version:\s*"([^"]+)"', cit_text, re.M)
    v_cit = m_cit.group(1) if m_cit else None
    if not (v_init == v_pipe == v_cit):
        errors.append(f"version mismatch: __init__={v_init}, pipeline={v_pipe}, CITATION.cff={v_cit}")

    # 2. Rule-text sync check
    sync_proc = subprocess.run([sys.executable, str(ROOT / "scripts/sync_rule_text.py"), "--check"],
                               capture_output=True, text=True)
    if sync_proc.returncode != 0:
        errors.append(f"sync_rule_text.py --check failed: {sync_proc.stdout} {sync_proc.stderr}")

    # 3. Bundled price-index and RPP CSV integrity
    for idx_name in ("r-cpi-u-rs", "cpi-u", "c-cpi-u"):
        try:
            inflation.load_price_index(idx_name)
        except Exception as exc:
            errors.append(f"price index {idx_name} integrity error: {exc}")
    try:
        rpp.price_parity_info()
    except Exception as exc:
        errors.append(f"RPP integrity error: {exc}")

    # 4. Compatibility audits for completed Rounds 103-119 and 121-189
    for r in (*range(103, 120), 121, 122, 123, 124, *range(126, 190)):
        if not (ROOT / f"docs/audits/round{r}_compatibility.md").exists():
            errors.append(f"missing docs/audits/round{r}_compatibility.md")
    if not (ROOT / "PLAN_ROUND_125.md").exists():
        errors.append("missing open plan PLAN_ROUND_125.md (N39 ACS 2021-2025 refresh)")

    # 4d. Recipe registry parity: every key in census.recipes.RECIPES has docs/recipes/<name>.md
    from census import recipes as _recipes
    for rname in sorted(_recipes.RECIPES):
        if not (ROOT / "docs/recipes" / f"{rname}.md").exists():
            errors.append(f"missing docs/recipes/{rname}.md for recipe {rname}")

    # 4c. Strict Layer B isolation: layer_b_openscholar must never import census
    lb_dir = ROOT / "layer_b_openscholar"
    if lb_dir.exists():
        imp_pat = re.compile(r"^\s*(from\s+census\b|import\s+census\b)", re.M)
        for pyf in sorted(lb_dir.rglob("*.py")):
            if imp_pat.search(pyf.read_text(encoding="utf-8")):
                errors.append(f"Layer B isolation violated in {pyf.relative_to(ROOT)}")

    # 4b. Citation key integrity for all manifest methods
    missing_cites = sorted({k for spec in METHODS.values() if spec.text for k in spec.text[1] if k not in SOURCES})
    if missing_cites:
        errors.append(f"missing manifest citation keys in census.references.SOURCES: {missing_cites}")

    # 5. Zero AI-attribution lines in release docs
    bad_pat = re.compile(r"Co-Authored-By:|Generated with Claude|Generated by AI", re.I)
    for rel in ("CHANGELOG.md", "STATUS.md", "ROADMAP_BACKLOG.md", "README.md"):
        txt = (ROOT / rel).read_text(encoding="utf-8")
        if bad_pat.search(txt):
            errors.append(f"AI-attribution string found in {rel}")

    return {
        "ok": len(errors) == 0,
        "version": v_init,
        "manifest_methods": len(METHODS),
        "errors": errors,
    }


def main():
    res = check_all()
    print(json.dumps(res, indent=2))
    sys.exit(0 if res["ok"] else 1)


if __name__ == "__main__":
    main()
